import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const src=fs.readFileSync('src/lib/ops.ts','utf8');
const js=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const ops=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const rows=(n,wrong=0)=>Array.from({length:n},(_,i)=>({id:String(i),unitId:'math-add',subject:'math',correct:i>=wrong,knowledge:'加减法',createdAt:new Date().toISOString(),question:'q',userAnswer:'a',explanation:'hint'}));
assert.equal(ops.mastery(rows(1),'math-add'),20);
assert.equal(ops.unitUnlocked(rows(4),'math-multiply'),false);
assert.equal(ops.unitUnlocked(rows(10,1),'math-multiply'),true);
assert.equal(ops.unitUnlocked(rows(10,2),'math-multiply'),false);
assert.equal(ops.unitUnlocked([],'unknown'),false);
assert.equal(ops.normalizeOps(undefined,120).xpTotal,120);
assert.match(ops.diagnose({correct:false,knowledge:'分数'}),/暂不能确定根因/);
assert.doesNotMatch(ops.guardMentorReply('正确答案是 5'),/答案是/);
const records=rows(250,20);
const context=ops.historyContext({practices:records,assessments:{},wrongBook:[]},'math');
assert.match(context,/"id":"249"/);
assert.equal(ops.weekStart(new Date(2026,9,4)),'2026-09-28');
const ledger=ops.initialOps(); ledger.awards=[{id:'a',subject:'math',at:'2026-09-30T12:00:00',amount:10},{id:'b',subject:'math',at:'2026-10-05T12:00:00',amount:20}];
